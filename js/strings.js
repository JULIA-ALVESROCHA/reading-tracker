/** Looks up a string by dotted path, e.g. t("nav.log"). Functions are called with args. */
export function t(path, ...args) {
  const value = path.split(".").reduce((obj, key) => (obj == null ? obj : obj[key]), STRINGS);
  if (typeof value === "function") return value(...args);
  return value ?? path;
}
